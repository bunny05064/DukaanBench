"""Emits rating_ui/data.js from prompts/prompts.json + q1_eval/images.

The UI must work from file:// with no server and no build step, so the prompt
spec and image inventory are compiled into a plain JS file instead of being
fetched at runtime.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.join(HERE, "prompts", "prompts.json")
IMG = os.path.join(HERE, "images")
OUT = os.path.join(HERE, "rating_ui", "data.js")


def main():
    spec = json.load(open(SPEC, encoding="utf-8"))
    def slug(s):
        out = "".join(c.lower() if c.isalnum() else "-" for c in s)
        while "--" in out:
            out = out.replace("--", "-")
        return out.strip("-")

    trials, not_run = [], []
    for p in spec["prompts"]:
        for m in spec["models"]:
            stem = f"{p['id']}__{slug(m['company'])}__{slug(m['model'])}"
            if not os.path.exists(os.path.join(IMG, stem + ".png")):
                not_run.append({
                    "trial_id": stem, "prompt_id": p["id"],
                    "company": m["company"], "model": m["model"],
                    "reason": m.get("reason") or spec["shared_settings"]["documented_gap"],
                })
                continue
            path = f"../images/{stem}.png"
            trials.append({
                "trial_id": stem,
                "prompt_id": p["id"],
                "axis": p["axis"],
                "prompt_text": p["text"],
                "must_contain": p["must_contain"],
                "must_show": p["must_show"],
                "image": path,
                "model_blind_key": m["model_id"],
            })

    payload = {
        "eval_name": spec["eval_name"],
        "eval_title": spec["eval_title"],
        "category": spec["category"],
        "use_case": spec["use_case"],
        "criteria": spec["criteria"],
        "shared_settings": spec["shared_settings"],
        "trials": trials,
        "not_run": not_run,
        "n_trials": len(trials),
        "n_models": sorted({t["model_blind_key"] for t in trials}),
        "scale": [1, 2, 3, 4, 5],
        "scale_labels": {
            "1": "Strongly disagree",
            "2": "Mostly disagree",
            "3": "Mixed / partly ok",
            "4": "Mostly agree",
            "5": "Strongly agree",
        },
        "no_text_note": "For prompts that say 'No text anywhere in the image', "
                        "score Text accuracy on whether the model correctly omitted "
                        "all text (5 = no text appeared, 1 = stray/wrong text appeared).",
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by build_ui_data.py - do not edit by hand.\n")
        fh.write("window.EVAL_DATA = ")
        json.dump(payload, fh, ensure_ascii=False, indent=2)
        fh.write(";\n")
    print(f"wrote {OUT} ({len(trials)} trials)")


if __name__ == "__main__":
    main()
