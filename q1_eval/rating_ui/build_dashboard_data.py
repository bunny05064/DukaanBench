#!/usr/bin/env python3
"""Build dashboard_data.js for the results dashboard.

Reads the 10 rater exports in rate_results/ and the trial/image index in data.js,
and writes rating_ui/dashboard_data.js with raw per-rating records so the
dashboard can compute any view (model, rater, criterion, prompt, image) client-side.

Run:  python3 q1_eval/rating_ui/build_dashboard_data.py
"""
import json
import glob
import os
import collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
EXPORT_GLOB = os.path.join(ROOT, "rate_results", "dukaanbench_ratings_*.json")
OUT = os.path.join(HERE, "dashboard_data.js")

CRITERIA = ["adherence", "fidelity", "text", "indiafit", "visual"]
MODEL_NAMES = {
    "gemini-2-5-flash-image": "Google — Gemini 2.5 Flash Image",
    "gemini-3-1-flash-image-preview": "Google — Gemini 3.1 Flash Image Preview",
    "gemini-3-pro-image": "Google — Gemini 3 Pro Image",
}
MODEL_ORDER = [
    "gemini-2-5-flash-image",
    "gemini-3-1-flash-image-preview",
    "gemini-3-pro-image",
]


def model_of(trial_id):
    return trial_id.split("__")[-1]


def load_trials():
    src = open(os.path.join(HERE, "data.js"), encoding="utf-8").read()
    obj = json.loads(src[src.index("{"):].rstrip().rstrip(";"))
    trials = []
    for t in obj["trials"]:
        trials.append({
            "trial_id": t["trial_id"],
            "prompt_id": t["prompt_id"],
            "axis": t.get("axis", ""),
            "model": model_of(t["trial_id"]),
            "image": t["image"],
        })
    return trials, obj


def main():
    trials, data = load_trials()
    trial_by_id = {t["trial_id"]: t for t in trials}
    prompt_axis = {t["prompt_id"]: t["axis"] for t in trials}

    raters, ratings = [], []
    for path in sorted(glob.glob(EXPORT_GLOB)):
        d = json.load(open(path, encoding="utf-8"))
        cons = d.get("consent") or {}
        name = cons.get("name") or os.path.basename(path)
        raters.append({
            "name": name,
            "email": cons.get("email", ""),
            "age": cons.get("age", ""),
            "file": os.path.basename(path),
        })
        for r in d["ratings"]:
            tid = r["trial_id"]
            if tid not in trial_by_id:
                continue
            row = {"rater": name, "trial_id": tid,
                   "prompt_id": r.get("prompt_id") or trial_by_id[tid]["prompt_id"],
                   "model": model_of(tid)}
            vals = [r.get(c) for c in CRITERIA]
            if any(v is None for v in vals):
                continue
            for c in CRITERIA:
                row[c] = int(r[c])
            row["overall"] = sum(row[c] for c in CRITERIA) / len(CRITERIA)
            ratings.append(row)

    models = [m for m in MODEL_ORDER
              if any(x["model"] == m for x in ratings)]
    prompts = sorted({t["prompt_id"] for t in trials},
                     key=lambda p: int(p[1:]))
    prompts = [{"id": p, "axis": prompt_axis.get(p, "")}
               for p in prompts if p in prompt_axis]

    out = {
        "eval_name": data.get("eval_name", "DukaanBench"),
        "criteria": [{"id": c, "name": data["criteria"][i]["name"]}
                     for i, c in enumerate(CRITERIA)],
        "models": [{"id": m, "name": MODEL_NAMES.get(m, m)} for m in models],
        "prompts": prompts,
        "raters": raters,
        "trials": trials,
        "ratings": ratings,
    }
    body = json.dumps(out, ensure_ascii=False, indent=2)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by build_dashboard_data.py - do not edit by hand.\n")
        fh.write("window.DASH = " + body + ";\n")
    print("wrote", OUT)
    print("raters=%d trials=%d ratings=%d models=%d" %
          (len(raters), len(trials), len(ratings), len(models)))


if __name__ == "__main__":
    main()
